#!/usr/bin/env python3
"""Build the station index from vendored data; see third_party/stations/README.md."""
import csv, json, re, unicodedata
from collections import defaultdict
from pathlib import Path
root=Path(__file__).resolve().parents[1]
def normalize(s):
    return unicodedata.normalize('NFKC',s).replace('ヶ','ケ')
readings=defaultdict(set)
with (root/'third_party/stations/readings.csv').open() as f:
    for r in csv.DictReader(f):
        kana=unicodedata.normalize('NFKC',r['kana']).replace('ぢ','じ').replace('づ','ず')
        kana=''.join(chr(ord(c)-0x60) if 'ァ'<=c<='ヶ' else c for c in kana)
        if re.fullmatch('[ぁ-ゔー]+',kana):readings[normalize(r['name'])].add(kana)
entries=defaultdict(set)
with (root/'third_party/stations/station_codes.csv').open() as f:
    for r in list(csv.reader(f))[1:]:
        region,line,station=(int(v,16) for v in r[:3])
        if region>3 or line>255 or station>255:continue
        name=r[5];kana=readings.get(normalize(name),set())
        # Do not guess ambiguous names (e.g. same kanji, different readings).
        if len(kana)==1:entries[(region<<16)|(line<<8)|station].add((name,next(iter(kana))))
lines=['// Generated by scripts/generate_stations.py; data: CC BY-SA 4.0.', '// Attribution and MIT source license: third_party/stations/README.md', 'static const Station stations[] = {']
for key,values in sorted(entries.items()):
    if len(values)!=1:continue
    name,kana=next(iter(values))
    lines.append('    {0x%06x, %s, %s},'%(key,json.dumps(name,ensure_ascii=False),json.dumps(kana,ensure_ascii=False)))
lines.append('};')
(root/'data/stations.inc').write_text('\n'.join(lines)+'\n')
print('Stations:',len(lines)-4)
